"""Generate state defaults and business event wiring from the retained MainWindow reference.
The output is C# data initialization; no XAML runtime/compiler is involved.
"""
from pathlib import Path
import json,re,xml.etree.ElementTree as ET
root=Path(__file__).resolve().parents[2]/'CelesteMusicPlayer'
tree=ET.parse(root/'_legacy_xaml/MainWindow.xaml.legacy')
fields=set(re.findall(r'internal [\w.]+ (\w+) = new', (root/'MainWindow.LegacyControls.cs').read_text(encoding='utf-8-sig')))
scalar={'Minimum','Maximum','StepFrequency','SmallChange','LargeChange','Value','SelectedIndex'}
boolprops={'IsOn','IsChecked','IsEnabled'}
events={'ValueChanged','Toggled','Checked','Unchecked','SelectionChanged'}
lines=[];hooks=[];seen=set();count=0
for el in tree.iter():
 name=el.get('{http://schemas.microsoft.com/winfx/2006/xaml}Name');tag=el.tag.split('}')[-1]
 if name not in fields or name in seen or tag not in {'Slider','ToggleSwitch','CheckBox','ComboBox','NumberBox'}:continue
 seen.add(name);count+=1
 for key in sorted(scalar-{'Value','SelectedIndex'})+['Value']:
  value=el.get(key)
  if value is not None and re.fullmatch(r'-?\d+(\.\d+)?',value):lines.append(f'            {name}.{key} = {value}'+(';' if key=='SelectedIndex' else 'd;'))
 for key in sorted(boolprops):
  value=el.get(key)
  if value in ('True','False','true','false'):lines.append(f'            {name}.{key} = {value.lower()};')
 if tag=='ComboBox':
  items=[c for c in el if c.tag.split('}')[-1]=='ComboBoxItem']
  for c in items:
   props=', '.join(k+' = '+json.dumps(c.get(k),ensure_ascii=False) for k in ['Content','Tag'] if c.get(k) is not None)
   lines.append(f'            {name}.Items.Add(new Microsoft.UI.Xaml.Controls.ComboBoxItem {{ {props} }});')
  if el.get('SelectedIndex') is not None:lines.append(f'            {name}.SelectedIndex = {int(el.get("SelectedIndex"))};')
 for event in sorted(events):
  handler=el.get(event)
  if handler and re.fullmatch(r'\w+',handler):hooks.append(f'            {name}.{event} += (sender, args) => {handler}((dynamic)sender, (dynamic)args);')
output='''// Generated by tools/GenerateLegacyBusinessState/generate.py.
// Defaults and business callbacks only; the retained XAML is not compiled or loaded.
namespace CelesteMusicPlayer {
    public sealed partial class MainWindow {
        private void InitializeLegacyBusinessState() {
'''+ '\n'.join(lines+hooks)+'\n        }\n    }\n}\n'
(root/'MainWindow.LegacyBusinessState.cs').write_text(output,encoding='utf-8-sig')
print(f'{count} state objects, {len(lines)} defaults/items, {len(hooks)} business event subscriptions')
