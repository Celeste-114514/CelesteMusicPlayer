def ns_of(ty):
    # 找 shim 里该类型的命名空间
    for m in re.finditer(r'namespace ([\w\.]+)\s*\{(.*?)\n\}\n', shim_src, re.S):
        if re.search(r'class\s+%s\b' % re.escape(ty), m.group(2)):
            return m.group(1)
    return None


