    m = re.match(r'^.*\\([A-Za-z0-9_\.]+\.cs)\((\d+),\d+\): error (CS\d+): (.*?)\s*\[', ln)
    if not m:
        continue
    code, msg = m.group(3), m.group(4)
    if code == 'CS1061':
        t = re.search(r'“([\w\.<>`]+)”未包含“(\w+)”', msg)
        if t:
            ty = t.group(1).split('.')[-1].replace('?', '')
            inst[ty].add(t.group(2))
    elif code == 'CS0117':
        t = re.search(r'“([\w\.<>`]+)”未包含“(\w+)”', msg)
        if t:
            ty = t.group(1).split('.')[-1].replace('?', '')
            member = t.group(2)
            if member.endswith('Property'):
                props[ty].add(member)
            else:
                stat[ty].add(member)
    elif code == 'CS0103':
        t = re.search(r'不存在名称“(\w+)”', msg)
        if t:
            names[t.group(1)] += 1

