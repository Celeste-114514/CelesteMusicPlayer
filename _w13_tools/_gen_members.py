def block(ns, group, static):
    body = []
    for ty in sorted(group):
        if ty in ('object', 'MainWindow', 'App', 'String', 'Int32', 'Double', 'Boolean'):
            continue
        body.append('    public partial class %s' % ty)
        body.append('    {')
        for member in sorted(group[ty]):
            if member in ('SetTop', 'SetLeft', 'SetRight', 'SetBottom', 'SetZIndex', 'GetTop', 'GetLeft',
                          'GetZIndex', 'SetColumn', 'SetRow', 'SetColumnSpan', 'SetRowSpan', 'GetColumn', 'GetRow'):
                body.append('        public static void %s(global::Microsoft.UI.Xaml.DependencyObject? element, double value) { }' % member)
            elif member.startswith('Set') and member not in ('Setters',):
                body.append('        public static void %s(global::Microsoft.UI.Xaml.DependencyObject? element, object? value) { }' % member)
            elif member == 'ShowAt':
                body.append('        public void ShowAt(global::Microsoft.UI.Xaml.DependencyObject? target) { }')
                body.append('        public void ShowAt(global::Microsoft.UI.Xaml.DependencyObject? target, object? placement) { }')
            elif member == 'CreateTimer':
                body.append('        public global::Microsoft.UI.Dispatching.DispatcherQueueTimer CreateTimer() => new global::Microsoft.UI.Dispatching.DispatcherQueueTimer();')
            else:
                prefix = 'static ' if static else ''
                body.append('        public %sobject? %s { get; set; }' % (prefix, member))
        body.append('    }')
        body.append('')
    if body:
        w('namespace %s' % ns)
        w('{')
        out.extend(body)
        w('}')
        w('')


