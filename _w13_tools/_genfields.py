import re

known = set()
src = open('LegacyWinUiShim.cs', encoding='utf-8').read()
for m in re.finditer(r'public (?:class|struct|enum|sealed class) ([\w]+)', src):
    known.add(m.group(1))

controls_ns = set(re.findall(r'public class ([\w]+) : (?:Control|ContentControl|Panel|Selector|IconElement|Microsoft\.UI\.Xaml\.FrameworkElement)', src))

lines = []
for ln in open('_shim_names.txt', encoding='utf-8').read().splitlines():
    if not ln.strip():
        continue
    name, tag = ln.split('\t')
    if tag in controls_ns:
        t = 'Microsoft.UI.Xaml.Controls.' + tag
    elif tag in ('Grid', 'StackPanel', 'Canvas', 'Border', 'Image', 'TextBlock', 'Run', 'Path'):
        t = 'Microsoft.UI.Xaml.Controls.' + tag
    elif tag in ('Rectangle', 'Ellipse', 'Line', 'Polygon', 'Polyline'):
        t = 'Microsoft.UI.Xaml.Shapes.' + tag
    elif tag in ('Storyboard', 'DoubleAnimation', 'SolidColorBrush', 'ThemeShadow', 'FontFamily'):
        t = 'Microsoft.UI.Xaml.Media.' + tag
    else:
        t = 'Microsoft.UI.Xaml.Controls.Control'
    lines.append('        internal %s %s = new();' % (t, name))

out = []
out.append('// <auto-generated>')
out.append('// W13 过渡：旧 XAML 界面的控件已改为纯状态容器（窗口长期隐藏，控件只存状态）。')
out.append('// 由 _genfields.py 从 _legacy_xaml/MainWindow.xaml.legacy 生成，后续按域清理时可整体删除。')
out.append('// </auto-generated>')
out.append('#pragma warning disable CS0169')
out.append('#pragma warning disable CS0414')
out.append('#pragma warning disable CS0649')
out.append('')
out.append('namespace CelesteMusicPlayer')
out.append('{')
out.append('    public sealed partial class MainWindow')
out.append('    {')
out.extend(lines)
out.append('    }')
out.append('}')
open('MainWindow.LegacyControls.cs', 'w', encoding='utf-8').write('\n'.join(out))
print('字段数:', len(lines))
